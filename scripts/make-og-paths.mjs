// One-off: draws the share-preview texts as vector outlines and writes lib/og-paths.ts.
//   "UC":                    Arial Bold, upright
//   "Ride the wave first.":  Arial Regular
// Both come from this Windows machine's installed Arial; only the outlines (a drawing) are committed,
// never the font files, which are Microsoft's.
// Run:  node scripts/make-og-paths.mjs
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const MARK = "UC";
const MARK_SIZE = 350; // px in the 1200 x 630 image; cap height is about 250
const TAGLINE = "Ride the wave first.";
const TAGLINE_SIZE = 56;

const parse = (file) => {
  const b = readFileSync(file);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};

const bold = parse("C:/Windows/Fonts/arialbd.ttf"); // Arial Bold
const regular = parse("C:/Windows/Fonts/arial.ttf"); // Arial Regular

// baseline at y = 0; widths are what the text occupies, for centering
const markPath = bold.getPath(MARK, 0, 0, MARK_SIZE);
const markBox = markPath.getBoundingBox();
const tagPath = regular.getPath(TAGLINE, 0, 0, TAGLINE_SIZE);
const tagBox = tagPath.getBoundingBox();
const tagCap = -regular.getPath("R", 0, 0, TAGLINE_SIZE).getBoundingBox().y1;

const data = {
  mark: { d: markPath.toPathData(2), x1: +markBox.x1.toFixed(1), x2: +markBox.x2.toFixed(1), capHeight: +(-markBox.y1).toFixed(1) },
  tagline: { d: tagPath.toPathData(2), x1: +tagBox.x1.toFixed(1), x2: +tagBox.x2.toFixed(1), capHeight: +tagCap.toFixed(1) },
};

console.log(`UC: ink ${data.mark.x1}..${data.mark.x2} (width ${(data.mark.x2 - data.mark.x1).toFixed(1)}), cap height ${data.mark.capHeight}`);
console.log(`tagline: ink ${data.tagline.x1}..${data.tagline.x2} (width ${(data.tagline.x2 - data.tagline.x1).toFixed(1)}), cap height ${data.tagline.capHeight}`);

writeFileSync(
  new URL("../lib/og-paths.ts", import.meta.url),
  `// Generated by scripts/make-og-paths.mjs from Arial. Outlines only, baseline at y = 0, in px of the 1200 x 630 preview.
// x1/x2 are where the ink starts and ends, so the text can be centered by its visible edges.
export const OG_MARK = ${JSON.stringify(data.mark)};
export const OG_TAGLINE = ${JSON.stringify(data.tagline)};
`,
);
console.log("wrote lib/og-paths.ts");
