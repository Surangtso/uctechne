// One-off: draws the share-preview texts as vector outlines and writes lib/og-paths.ts.
//   wordmark "UCtechne": Verdana Bold, from this Windows machine's installed font (outlines only are committed)
//   description: Noto Sans KR Bold (SIL OFL), taken from the @fontsource/noto-sans-kr slice that holds each glyph
// Run:  node scripts/make-og-paths.mjs
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const WORDMARK = "UCtechne";
const WORDMARK_WIDTH = 560; // px in the 1200 x 630 image
const DESC_LINES = ["기술의 큰 흐름에", "가장 먼저 올라타기"];
const DESC_SIZE = 54; // previews are often shown small, so the description is not tiny

const parse = (file) => {
  const b = readFileSync(file);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};

// --- wordmark
const verdana = parse("C:/Windows/Fonts/verdanab.ttf"); // Verdana Bold
const adv100 = verdana.getAdvanceWidth(WORDMARK, 100);
const wmSize = (WORDMARK_WIDTH / adv100) * 100;
const wmPath = verdana.getPath(WORDMARK, 0, 0, wmSize);
const wmCap = -verdana.getPath("U", 0, 0, wmSize).getBoundingBox().y1;
const wmWidth = verdana.getAdvanceWidth(WORDMARK, wmSize);

// --- description: find the font slice that covers each character
const css = readFileSync("node_modules/@fontsource/noto-sans-kr/700.css", "utf8");
const slices = [...css.matchAll(/url\(\.\/files\/(noto-sans-kr-\d+-700-normal)\.woff2\)[^;]*;\s*unicode-range:\s*([^;]+);/g)].map((m) => ({
  file: `node_modules/@fontsource/noto-sans-kr/files/${m[1]}.woff`,
  ranges: m[2].split(",").map((r) => {
    const [a, b] = r.trim().replace(/^U\+/i, "").split("-");
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  }),
}));
const fonts = new Map();
const fontFor = (code) => {
  const s = slices.find((sl) => sl.ranges.some(([a, b]) => code >= a && code <= b));
  if (!s) throw new Error(`no slice covers U+${code.toString(16)}`);
  if (!fonts.has(s.file)) fonts.set(s.file, parse(s.file));
  return fonts.get(s.file);
};

function line(text) {
  let x = 0;
  let d = "";
  for (const ch of text) {
    if (ch === " ") {
      x += DESC_SIZE * 0.28;
      continue;
    }
    const f = fontFor(ch.codePointAt(0));
    const g = f.charToGlyph(ch);
    d += g.getPath(x, 0, DESC_SIZE).toPathData(2);
    x += (g.advanceWidth * DESC_SIZE) / f.unitsPerEm;
  }
  return { d, width: +x.toFixed(1) };
}
const lines = DESC_LINES.map(line);

console.log(`wordmark: size ${wmSize.toFixed(1)}px, width ${wmWidth.toFixed(1)}, cap height ${wmCap.toFixed(1)}`);
lines.forEach((l, i) => console.log(`desc line ${i + 1}: width ${l.width}`));

writeFileSync(
  new URL("../lib/og-paths.ts", import.meta.url),
  `// Generated by scripts/make-og-paths.mjs. Outlines only, baseline at y = 0, in px of the 1200 x 630 preview.
export const OG_WORDMARK = { d: ${JSON.stringify(wmPath.toPathData(2))}, width: ${+wmWidth.toFixed(1)}, capHeight: ${+wmCap.toFixed(1)} };
export const OG_DESC = ${JSON.stringify(lines, null, 2)};
`,
);
console.log("wrote lib/og-paths.ts");
