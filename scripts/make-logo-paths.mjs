// One-off: turns the letters U and C of Verdana Bold Italic into vector outlines and writes lib/logo-paths.ts.
// Only the outlines (a drawing of the letters) are committed, never the font file, which is Microsoft's.
// Run on a Windows machine that has Verdana installed:  node scripts/make-logo-paths.mjs
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const FONT = "C:/Windows/Fonts/verdanaz.ttf"; // Verdana Bold Italic
const SIZE = 100; // outline resolution only
const CAP = 40; // height of each letter in the 100 x 100 logo box
const MARGIN = 7;

const buf = readFileSync(FONT);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const glyph = (ch) => font.getPath(ch, 0, 0, SIZE);
const u = glyph("U");
const c = glyph("C");
const ub = u.getBoundingBox();
const cb = c.getBoundingBox();

// one scale for both letters so they have the same size; U's height defines it
const s = CAP / (ub.y2 - ub.y1);

function place(path, tx, ty) {
  const f = (x, y) => [x * s + tx, y * s + ty];
  const n = (v) => +v.toFixed(2);
  return path.commands
    .map((cmd) => {
      if (cmd.type === "Z") return "Z";
      if (cmd.type === "M" || cmd.type === "L") return `${cmd.type}${f(cmd.x, cmd.y).map(n).join(" ")}`;
      if (cmd.type === "Q") return `Q${[...f(cmd.x1, cmd.y1), ...f(cmd.x, cmd.y)].map(n).join(" ")}`;
      return `C${[...f(cmd.x1, cmd.y1), ...f(cmd.x2, cmd.y2), ...f(cmd.x, cmd.y)].map(n).join(" ")}`;
    })
    .join("");
}

// U: top-left corner of its box at (MARGIN, MARGIN). C: bottom-right corner at (100 - MARGIN, 100 - MARGIN).
const uPath = place(u, MARGIN - ub.x1 * s, MARGIN - ub.y1 * s);
const cPath = place(c, 100 - MARGIN - cb.x2 * s, 100 - MARGIN - cb.y2 * s);

const uw = (ub.x2 - ub.x1) * s;
const cw = (cb.x2 - cb.x1) * s;
const ch = (cb.y2 - cb.y1) * s;
console.log(`U box: ${MARGIN}..${(MARGIN + uw).toFixed(1)} x ${MARGIN}..${(MARGIN + CAP).toFixed(1)}`);
console.log(`C box: ${(100 - MARGIN - cw).toFixed(1)}..${100 - MARGIN} x ${(100 - MARGIN - ch).toFixed(1)}..${100 - MARGIN}`);

writeFileSync(
  new URL("../lib/logo-paths.ts", import.meta.url),
  `// Generated by scripts/make-logo-paths.mjs from Verdana Bold Italic. Outlines only, in a 100 x 100 box.
export const LOGO_U = ${JSON.stringify(uPath)};
export const LOGO_C = ${JSON.stringify(cPath)};
`,
);
console.log("wrote lib/logo-paths.ts");
